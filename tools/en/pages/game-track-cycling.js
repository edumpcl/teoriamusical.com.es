<p>Telling by ear whether a melody is in a major or a minor key is one of the first questions in dictation and in conservatory ear-training tests. What decides it is the <strong>3rd above the tonic</strong>: a major 3rd in a major key and a minor 3rd in a minor key. The melodies start with the tonic arpeggio, so the first measure already gives away the answer; with practice you recognize it right away, which is exactly what the clock rewards. If you would rather practice without pressure, there is the <a href="/ejercicios/auditivos/mayor-o-menor/">Major or Minor? exercise</a>, which shows the written score of each melody, and to review the theory, the difference between the <a href="/diccionario-musical/tonalidades/escalas-mayores/">major scale</a> and the <a href="/diccionario-musical/tonalidades/escalas-menores/">minor scale</a>.</p>

